"""Board-ready reports: the overall compliance posture, or one system assessment, as PDF or Word.

A report is built once as a list of blocks and rendered by either writer, so both formats say the same thing.
"""
from dataclasses import dataclass, field
from datetime import datetime, timezone
from io import BytesIO

import psycopg


@dataclass
class Table:
    headers: list[str]
    rows: list[list[str]]
    widths: list[float] | None = None    # relative column widths


@dataclass
class Report:
    title: str
    subtitle: str
    blocks: list = field(default_factory=list)   # ("h", text) ("p", text) ("bullets", [..]) ("kpis", [(label, value)]) Table

    def heading(self, text):
        self.blocks.append(("h", text))

    def paragraph(self, text):
        self.blocks.append(("p", text))

    def bullets(self, items):
        if items:
            self.blocks.append(("bullets", list(items)))

    def kpis(self, items):
        self.blocks.append(("kpis", list(items)))

    def table(self, headers, rows, widths=None, empty="None."):
        if rows:
            self.blocks.append(Table(headers, [[_text(cell) for cell in row] for row in rows], widths))
        else:
            self.paragraph(empty)


def _text(value) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:.0%}" if value <= 1 else f"{value:.1f}"
    if isinstance(value, datetime):
        return value.strftime("%d %b %Y")
    return str(value)


def _title(value: str | None) -> str:
    return value.replace("_", " ").capitalize() if value else "—"


NOTICE = ("Generated by ClauseIQ from AI-assisted analysis. Findings marked pending have not been reviewed. "
          "Document-level assessment only: it does not establish that controls operate in practice.")


# ---------------------------------------------------------------- content

def posture_report(database_url: str, generated_by: str | None = None) -> Report:
    with psycopg.connect(database_url, connect_timeout=10) as connection:
        q = lambda sql, *args: connection.execute(sql, args).fetchall()  # noqa: E731
        circulars = q("""
            SELECT d.regulator, count(DISTINCT d.id), count(o.id) FILTER (WHERE o.lifecycle_status = 'ACTIVE'),
                   count(o.id) FILTER (WHERE o.lifecycle_status = 'RETIRED')
            FROM regulatory_document d LEFT JOIN obligation o ON o.document_id = d.id
            GROUP BY d.regulator ORDER BY 2 DESC""")
        by_status = dict(q("SELECT status, count(*) FROM finding GROUP BY status"))
        open_by_severity = dict(q("""
            SELECT severity, count(*) FROM finding WHERE status = 'PENDING_REVIEW' GROUP BY severity"""))
        top = q("""
            SELECT f.severity, f.title, d.regulator || ': ' || d.title, r.assigned_role,
                   coalesce(o.deadline, r.suggested_deadline || ' (suggested)')
            FROM finding f JOIN obligation o ON o.id = f.obligation_id
            JOIN regulatory_document d ON d.id = f.document_id
            LEFT JOIN recommendation r ON r.finding_id = f.id
            WHERE f.status = 'PENDING_REVIEW'
            ORDER BY array_position(ARRAY['HIGH', 'MEDIUM', 'LOW'], f.severity), f.confidence DESC LIMIT 15""")
        decisions = q("""
            SELECT decision, count(*) FROM review_decision WHERE decided_at > now() - interval '30 days'
            GROUP BY decision ORDER BY 2 DESC""") if _exists(connection, "review_decision") else []
        approved_actions = q("""
            SELECT r.assigned_role, count(*) FROM finding f JOIN recommendation r ON r.finding_id = f.id
            WHERE f.status IN ('APPROVED', 'APPROVED_WITH_CHANGES') GROUP BY 1 ORDER BY 2 DESC""")
        changes = q("""
            SELECT l.relation, s.regulator || ': ' || s.title, coalesce(t.regulator || ': ' || t.title, l.cited_identifier),
                   l.status, l.retired_obligations
            FROM circular_link l JOIN regulatory_document s ON s.id = l.source_document_id
            LEFT JOIN regulatory_document t ON t.id = l.target_document_id
            WHERE l.relation <> 'REFERS_TO' AND l.status <> 'DISMISSED'
            ORDER BY l.status DESC, l.created_at DESC LIMIT 12""")
        systems = q("""
            SELECT DISTINCT ON (a.name) a.name, a.completed_at,
                   (SELECT count(*) FROM system_finding f WHERE f.assessment_id = a.id AND f.status <> 'MEETS'),
                   (SELECT count(*) FROM system_finding f WHERE f.assessment_id = a.id AND f.severity = 'HIGH')
            FROM system_assessment a WHERE a.status = 'COMPLETED' ORDER BY a.name, a.completed_at DESC""")
        scans = q("""
            SELECT DISTINCT ON (s.target) s.target, s.created_at,
                   (SELECT count(*) FROM data_scan_field f WHERE f.scan_id = s.id),
                   (SELECT count(*) FROM data_scan_field f WHERE f.scan_id = s.id AND f.sensitivity = 'HIGH' AND NOT f.protected)
            FROM data_scan s WHERE s.status = 'COMPLETED' ORDER BY s.target, s.created_at DESC""")

    pending = by_status.get("PENDING_REVIEW", 0)
    report = Report("Regulatory compliance posture", _subtitle(generated_by))
    report.heading("Summary")
    report.kpis([("Circulars", sum(row[1] for row in circulars)),
                 ("Active obligations", sum(row[2] for row in circulars)),
                 ("Findings awaiting review", pending), ("High severity awaiting review", open_by_severity.get("HIGH", 0)),
                 ("Approved actions", by_status.get("APPROVED", 0) + by_status.get("APPROVED_WITH_CHANGES", 0)),
                 ("Retired obligations", sum(row[3] for row in circulars))])
    report.paragraph(
        f"ClauseIQ has extracted obligations from {sum(row[1] for row in circulars)} circulars and compared them with "
        f"the approved policy handbook and control register. {pending} findings await a reviewer's decision, "
        f"{open_by_severity.get('HIGH', 0)} of them high severity.")
    report.heading("Coverage by regulator")
    report.table(["Regulator", "Circulars", "Active obligations", "Retired obligations"],
                 [list(row) for row in circulars], [2, 1, 1.4, 1.4])
    report.heading("Highest priority findings awaiting review")
    report.table(["Severity", "Finding", "Circular", "Owner", "Deadline"],
                 [[_title(row[0]), row[1], row[2], row[3], row[4]] for row in top], [0.8, 2.4, 2.4, 1.3, 1.2],
                 empty="No findings await review.")
    report.heading("Review activity in the last 30 days")
    report.table(["Decision", "Count"], [[_title(row[0]), row[1]] for row in decisions], [3, 1],
                 empty="No review decisions in the last 30 days.")
    report.heading("Approved actions by owner")
    report.table(["Owner", "Approved actions"], [list(row) for row in approved_actions], [3, 1],
                 empty="No approved actions yet.")
    report.heading("Circular changes")
    report.table(["Change", "New circular", "Earlier circular", "Status", "Obligations retired"],
                 [[_title(row[0]), row[1], row[2], _title(row[3]), row[4]] for row in changes], [1, 2.4, 2.4, 1, 1],
                 empty="No supersessions or amendments detected.")
    report.heading("System assessments")
    report.table(["System", "Assessed", "Open findings", "High severity"], [list(row) for row in systems], [2.5, 1, 1, 1],
                 empty="No completed system assessments.")
    report.heading("Sensitive data discovery")
    report.table(["Database", "Scanned", "Sensitive fields", "Unprotected high-sensitivity fields"],
                 [list(row) for row in scans], [2, 1, 1, 1.6], empty="No database scans.")
    report.paragraph(NOTICE)
    return report


def system_report(assessment: dict, generated_by: str | None = None) -> Report:
    report = Report(f"System assessment: {assessment['name']}", _subtitle(generated_by))
    stats = assessment["stats"]
    open_findings = [item for item in assessment["findings"] if item["status"] != "MEETS"]
    report.heading("Summary")
    report.kpis([("Obligations compared", stats["compared"]), ("Open findings", stats["open"]),
                 ("High severity", sum(1 for item in open_findings if item["severity"] == "HIGH")),
                 ("Meets", stats["meets"]), ("Not applicable", stats["notApplicable"]),
                 ("System facts read", stats["facts"])])
    report.paragraph(
        f"The system's design documents were compared with {stats['compared']} obligations from ingested circulars. "
        f"{stats['open']} need attention and {stats['meets']} appear to be met by the documented design.")
    report.heading("Documents assessed")
    report.table(["Document", "File", "Read by", "Facts"],
                 [[_title(item["kind"]), item["filename"], "Vision model" if item["method"] == "VISION" else "Text",
                   item["factCount"]] for item in assessment["artifacts"]], [1.4, 2.4, 1.2, 0.8])
    report.heading("Improvement plan")
    if not assessment["plan"]:
        report.paragraph("No open findings.")
    for phase in assessment["plan"]:
        report.blocks.append(("h2", f"{phase['phase']} ({phase['window']})"))
        report.table(["Improvement", "Owner", "Effort", "Circular"],
                     [[f"{item['title']}: {item['improvement']}", item["ownerRole"], _title(item["effort"]),
                       f"{item['circular']['regulator']}: {item['circular']['title']}"] for item in phase["items"]],
                     [3.4, 1.3, 0.8, 2])
    report.heading("Findings")
    report.table(["Severity", "Result", "Finding", "Obligation", "System evidence"],
                 [[_title(item["severity"]) if item["severity"] else "Covered", _title(item["status"]), item["title"],
                   f"{item['obligation']['summary']} ({item['obligation']['circular']['regulator']})",
                   item["systemQuote"] or (item["evidence"][0]["content"] if item["evidence"] else "—")]
                  for item in assessment["findings"]], [0.8, 0.9, 1.6, 2.4, 2.4])
    report.paragraph(NOTICE + " Diagram evidence was read by a vision model and should be checked against the diagram.")
    return report


def _exists(connection, table: str) -> bool:
    return connection.execute("SELECT to_regclass(%s) IS NOT NULL", (table,)).fetchone()[0]


def _subtitle(generated_by: str | None) -> str:
    stamp = datetime.now(timezone.utc).strftime("%d %B %Y, %H:%M UTC")
    return f"Generated {stamp}" + (f" by {generated_by}" if generated_by else "")


