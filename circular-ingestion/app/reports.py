def to_pdf(report: Report) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer
    from reportlab.platypus import Table as PdfTable
    from reportlab.platypus import TableStyle
    from xml.sax.saxutils import escape

    styles = getSampleStyleSheet()
    body = ParagraphStyle("body", parent=styles["BodyText"], fontSize=9.5, leading=12.5)
    cell = ParagraphStyle("cell", parent=body, fontSize=8.5, leading=10.5)
    head = ParagraphStyle("head", parent=cell, textColor=colors.white, fontName="Helvetica-Bold")
    navy = colors.HexColor("#1b2740")
    page = landscape(A4)
    width = page[0] - 30 * mm
    story = [Paragraph(escape(report.title), styles["Title"]), Paragraph(escape(report.subtitle), styles["Italic"]),
             Spacer(1, 4 * mm)]
    for block in report.blocks:
        if isinstance(block, Table):
            weights = block.widths or [1] * len(block.headers)
            data = [[Paragraph(escape(text), head) for text in block.headers]] + \
                   [[Paragraph(escape(text), cell) for text in row] for row in block.rows]
            table = PdfTable(data, colWidths=[width * weight / sum(weights) for weight in weights], repeatRows=1)
            table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), navy), ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#c9d1dc")),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f3f6f9")])]))
            story += [table, Spacer(1, 4 * mm)]
            continue
        kind, value = block
        if kind == "h":
            story.append(Paragraph(escape(value), styles["Heading2"]))
        elif kind == "h2":
            story.append(Paragraph(escape(value), styles["Heading3"]))
        elif kind == "p":
            story += [Paragraph(escape(value), body), Spacer(1, 2 * mm)]
        elif kind == "bullets":
            story += [Paragraph("• " + escape(item), body) for item in value]
        elif kind == "kpis":
            data = [[Paragraph(f"<font size=16><b>{escape(_text(number))}</b></font><br/>{escape(label)}", cell)
                     for label, number in value]]
            table = PdfTable(data, colWidths=[width / len(value)] * len(value))
            table.setStyle(TableStyle([("BOX", (0, 0), (-1, -1), 0.6, navy),
                                       ("INNERGRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#c9d1dc")),
                                       ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))
            story += [table, Spacer(1, 4 * mm)]

    def footer(canvas, document):
        canvas.saveState()
        canvas.setFont("Helvetica", 7.5)
        canvas.setFillColor(colors.HexColor("#6b7280"))
        canvas.drawString(15 * mm, 8 * mm, f"ClauseIQ · {report.title}")
        canvas.drawRightString(page[0] - 15 * mm, 8 * mm, f"Page {document.page}")
        canvas.restoreState()

    buffer = BytesIO()
    SimpleDocTemplate(buffer, pagesize=page, title=report.title, author="ClauseIQ", leftMargin=15 * mm,
                      rightMargin=15 * mm, topMargin=14 * mm, bottomMargin=16 * mm).build(
        story, onFirstPage=footer, onLaterPages=footer)
    return buffer.getvalue()


def to_docx(report: Report) -> bytes:
    from docx import Document
    from docx.enum.section import WD_ORIENT
    from docx.shared import Mm, Pt, RGBColor

    document = Document()
    section = document.sections[0]
    section.orientation = WD_ORIENT.LANDSCAPE
    section.page_width, section.page_height = Mm(297), Mm(210)
    for side in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
        setattr(section, side, Mm(15))
    document.styles["Normal"].font.size = Pt(10)
    document.add_heading(report.title, level=0)
    subtitle = document.add_paragraph(report.subtitle)
    subtitle.runs[0].italic = True
    usable = 267
    for block in report.blocks:
        if isinstance(block, Table):
            weights = block.widths or [1] * len(block.headers)
            table = document.add_table(rows=1, cols=len(block.headers))
            table.style = "Light Grid Accent 1"
            for index, text in enumerate(block.headers):
                table.rows[0].cells[index].text = text
                table.rows[0].cells[index].paragraphs[0].runs[0].bold = True
            for row in block.rows:
                cells = table.add_row().cells
                for index, text in enumerate(row):
                    cells[index].text = text
            for row in table.rows:
                for index, item in enumerate(row.cells):
                    item.width = Mm(usable * weights[index] / sum(weights))
                    for paragraph in item.paragraphs:
                        for run in paragraph.runs:
                            run.font.size = Pt(8.5)
            document.add_paragraph()
            continue
        kind, value = block
        if kind == "h":
            document.add_heading(value, level=1)
        elif kind == "h2":
            document.add_heading(value, level=2)
        elif kind == "p":
            document.add_paragraph(value)
        elif kind == "bullets":
            for item in value:
                document.add_paragraph(item, style="List Bullet")
        elif kind == "kpis":
            table = document.add_table(rows=2, cols=len(value))
            table.style = "Table Grid"
            for index, (label, number) in enumerate(value):
                run = table.rows[0].cells[index].paragraphs[0].add_run(_text(number))
                run.bold, run.font.size = True, Pt(16)
                run.font.color.rgb = RGBColor(0x1B, 0x27, 0x40)
                table.rows[1].cells[index].text = label
            document.add_paragraph()
    buffer = BytesIO()
    document.save(buffer)
    return buffer.getvalue()


RENDERERS = {"pdf": ("application/pdf", to_pdf),
             "docx": ("application/vnd.openxmlformats-officedocument.wordprocessingml.document", to_docx)}
